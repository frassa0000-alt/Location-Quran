/**
 * Intelligent matcher that finds the most relevant authoritative answer
 */
export function getSmartIslamicAnswer(userInput: string, ownerEmail: string = 'frassa0000@gmail.com'): string {
  const raw = userInput.trim();
  const normalized = normalizeArabic(raw);

  if (!normalized) {
    return 'تفضل بطرح سؤالك حول القرآن الكريم أو الفقه أو السنة النبوية أو أي مسألة عامة وسأجيبك فوراً وبدقة.';
  }

  // Check for issue reporting or website complaints
  if (
    normalized.includes('مشكله') ||
    normalized.includes('عطل') ||
    normalized.includes('صاحب الموقع') ||
    normalized.includes('مش شغال') ||
    normalized.includes('خطا') ||
    normalized.includes('بلغ') ||
    normalized.includes('شكوي')
  ) {
    return `إذا واجهت أي عطل أو مشكلة في الموقع، يمكنك الضغط على زر «إرسال لصاحب الموقع» أو مراسلته مباشرة عبر بريده الإلكتروني: ${ownerEmail}.`;
  }

  // Specific prayer queries (e.g. "كم عدد ركعات صلاة الفجر")
  if (normalized.includes('فجر') && (normalized.includes('ركع') || normalized.includes('كم'))) {
    return 'صلاة الفجر (الصبح) ركعتان مفروضتان، وتسبقها سنة الفجر القبلية وهي ركعتان مؤكدتان وفضلهما خير من الدنيا وما فيها.';
  }
  if (normalized.includes('ظهر') && (normalized.includes('ركع') || normalized.includes('كم'))) {
    return 'صلاة الظهر 4 ركعات مفروضة، وسنتها الراتبة 4 ركعات قبلها وركعتان بعدها.';
  }
  if (normalized.includes('عصر') && (normalized.includes('ركع') || normalized.includes('كم'))) {
    return 'صلاة العصر 4 ركعات مفروضة، وسنتها المستحبة 4 ركعات قبلها.';
  }
  if (normalized.includes('مغرب') && (normalized.includes('ركع') || normalized.includes('كم'))) {
    return 'صلاة المغرب 3 ركعات مفروضة، وسنتها الراتبة ركعتان بعدها.';
  }
  if (normalized.includes('عشاء') && (normalized.includes('ركع') || normalized.includes('كم'))) {
    return 'صلاة العشاء 4 ركعات مفروضة، وسنتها الراتبة ركعتان بعدها، ثم يتبعها صلاة الشفع والوتر.';
  }

  // Exact or keyword matching across database (with token-set matching)
  let bestMatch: QAEntry | null = null;
  let maxScore = 0;

  for (const entry of QA_DATABASE) {
    for (const kw of entry.keywords) {
      const normKw = normalizeArabic(kw);
      if (normalized === normKw) {
        return entry.response;
      }
      if (normalized.includes(normKw)) {
        const score = normKw.length * 2;
        if (score > maxScore) {
          maxScore = score;
          bestMatch = entry;
        }
      } else {
        // Multi-word token match: check if every individual word of the keyword is in the user query
        const words = normKw.split(' ').filter((w) => w.length > 2);
        if (words.length >= 2 && words.every((w) => normalized.includes(w))) {
          const score = words.reduce((acc, w) => acc + w.length, 0);
          if (score > maxScore) {
            maxScore = score;
            bestMatch = entry;
          }
        }
      }
    }
  }

  if (bestMatch && maxScore >= 4) {
    return bestMatch.response;
  }

  // Contextual synthesis for common question forms
  if (normalized.startsWith('ما حكم') || normalized.startsWith('حكم') || normalized.includes('هل يجوز')) {
    return `بشأن حكم «${raw}»: الأحكام الشرعية تبنى على الدليل من الكتاب والسنة وإجماع أهل العلم. الأصل في العبادات التوقيف، والأصل في المعاملات الإباحة ما لم يرد دليل بالتحريم. وللفتوى الدقيقة في المسائل الخاصة يُنصح بالرجوع إلى دار الإفتاء أو كبار العلماء المعتمدين.`;
  }

  if (normalized.startsWith('ما فضل') || normalized.startsWith('فضل')) {
    return `فضل ذلك عظيم؛ فالطاعات والذكر والاستغفار وتلاوة القرآن أبواب واسعة لنيل رضا الله ومغفرته ورفع الدرجات في الجنة: ﴿فَاذْكُرُونِي أَذْكُرْكُمْ وَاشْكُرُوا لِي وَلَا تَكْفُرُونِ﴾ [البقرة: 152].`;
  }

  if (normalized.startsWith('كيف') || normalized.includes('طريقه')) {
    return `بشأن سؤالك حول «${raw}»: المنهج الصحيح يقوم على اتباع هدي النبي ﷺ والتحري في العلم والعمل، والبدء بالأساسيات والفرائض ثم النوافل. يمكنك توضيح نقطة معينة تريد تفصيلها وسأشرحها لك فوراً.`;
  }

  if (normalized.startsWith('من هو') || normalized.startsWith('من هي')) {
    return `بشأن استفسارك عن «${raw}»: الإسلام يزخر بالأعلام والأنبياء والصحابة والعلماء الذين خدموا الدين والأمة وخلّد التاريخ سيرتهم العطرة. إذا كنت تسأل عن شخصية معينة حدد الاسم وسأذكر لك ملخص سيرته فوراً.`;
  }

  if (normalized.includes('تفسير') || normalized.includes('معني ايه') || normalized.includes('معني كلمه')) {
    return `تفسير كتاب الله يعتمد على فهم القرآن بالقرآن، ثم بالسنة النبوية الصحيحة، ثم بأقوال الصحابة ولسان العرب، وتفاسير المعتمدين مثل ابن كثير والطبري والسعدي. اكتب الآية الكريمة وسأذكر لك تفسيرها الميسر.`;
  }

  // High-utility concise direct response
  return `سؤالك: «${raw}». للإجابة بدقة: يُرجى تحديد تفاصيل أكثر أو كتابة السؤال بكلمات مباشرة مثل (ما حكم، كم عدد، ما فضل، كيف)، وسأجيبك بأدق تفصيل شرعي أو علمي فوراً وبلا تأخير.`;
}
