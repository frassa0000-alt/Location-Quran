// Normalize Arabic text for reliable matching
export function normalizeArabic(text: string): string {
  if (!text) return '';
  return text
    .toLowerCase()
    .replace(/[\u064B-\u065F\u0670]/g, '') // remove tashkeel
    .replace(/[إأآا]/g, 'ا')
    .replace(/ة/g, 'ه')
    .replace(/ى/g, 'ي')
    .replace(/[\?؟!,.:;،]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

