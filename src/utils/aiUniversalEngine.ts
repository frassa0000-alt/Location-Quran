// Normalize Arabic text for robust semantic matching
export function normalizeText(text: string): string {
  if (!text) return '';
  return text
    .toLowerCase()
    .replace(/[\u064B-\u065F\u0670]/g, '') // remove Arabic tashkeel
    .replace(/[إأآا]/g, 'ا')
    .replace(/ة/g, 'ه')
    .replace(/ى/g, 'ي')
    .replace(/[؟?!\.,:;،]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

// Math expression evaluator for calculations
export function tryEvaluateMath(prompt: string): string | null {
  const clean = prompt
    .replace(/احسب|ما هو ناتج|كم ناتج|كم يساوي|احسب لي|حل|ما ناتج|كم/g, '')
    .replace(/×/g, '*')
    .replace(/÷/g, '/')
    .replace(/ضرب/g, '*')
    .replace(/قسمة|على/g, '/')
    .replace(/زائد|جمع/g, '+')
    .replace(/ناقص|طرح/g, '-')
    .trim();

  // Match simple arithmetic: e.g., 25 * 4, 150 + 230, 100 / 5, 2^8, sqrt(64)
  const mathRegex = /^[-+/*0-9\s().^%]+$/;
  if (mathRegex.test(clean) && /[0-9]/.test(clean) && /[-+/*%^]/.test(clean)) {
    try {
      const sanitized = clean.replace(/\^/g, '**');
      // safe eval with Function for arithmetic only
      const result = new Function(`return (${sanitized})`)();
      if (typeof result === 'number' && !isNaN(result) && isFinite(result)) {
        return `الناتج الحسابي:\n${clean} = ${Number(result.toFixed(6))}`;
      }
    } catch {
      // ignore
    }
  }

  // Percentage: "كم 15% من 200" or "15 بالمئة من 200"
  const percentMatch = prompt.match(/(\d+(?:\.\d+)?)\s*(?:%|بالمائة|بالمئة|بالميه)\s*(?:من)?\s*(\d+(?:\.\d+)?)/);
  if (percentMatch) {
    const rate = parseFloat(percentMatch[1]);
    const total = parseFloat(percentMatch[2]);
    const val = (rate / 100) * total;
    return `حساب النسبة المئوية:\n${rate}% من ${total} = ${val}`;
  }

  return null;
}

